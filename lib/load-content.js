/**
 * lib/load-content.js
 * ----------------------------------------------------------------------------
 * Reads the raw content files in /content (YAML and JSON) from disk.
 *
 * This module only LOADS files. Shaping the data for pages happens in
 * lib/catalog.js, so the same raw content can be reused by the website build
 * (src/_data/catalog.js), the validation script and the maintenance scripts.
 */

const fs = require("node:fs");
const path = require("node:path");
const yaml = require("js-yaml");

/** Absolute path of the folder that holds every editable content file. */
const CONTENT_DIR = path.join(__dirname, "..", "content");

/**
 * Parses one YAML file from the content folder.
 *
 * Call it when you need a single file (e.g. a script that only touches
 * articles). Returns `fallback` when the file does not exist, so optional
 * files such as vizzes.json can be missing during first-time setup.
 *
 * @param {string} fileName  File name inside /content, e.g. "articles.yaml".
 * @param {*} [fallback]     Value returned when the file is missing.
 * @returns {*} The parsed YAML document.
 */
function loadYaml(fileName, fallback = undefined) {
  const filePath = path.join(CONTENT_DIR, fileName);
  if (!fs.existsSync(filePath)) {
    if (fallback !== undefined) return fallback;
    throw new Error(`Missing content file: ${filePath}`);
  }
  let data;
  try {
    data = yaml.load(fs.readFileSync(filePath, "utf8"), { filename: `content/${fileName}` });
  } catch (error) {
    // js-yaml's message already names the line and column and shows the
    // offending lines; say which file it is and what usually causes it.
    throw new Error(
      `content/${fileName} is not valid YAML. ${error.message}\n` +
        `Common causes: a value containing ": " or starting with a quote mark that is not wrapped in quotes, or wrong indentation.`,
    );
  }
  if (data === null || data === undefined) {
    if (fallback !== undefined) return fallback;
    throw new Error(`content/${fileName} is empty`);
  }
  return data;
}

/**
 * Parses one JSON file from the content folder (used for generated data such
 * as vizzes.json). Same contract as loadYaml().
 *
 * @param {string} fileName  File name inside /content.
 * @param {*} [fallback]     Value returned when the file is missing.
 * @returns {*} The parsed JSON document.
 */
function loadJson(fileName, fallback = undefined) {
  const filePath = path.join(CONTENT_DIR, fileName);
  if (!fs.existsSync(filePath)) {
    if (fallback !== undefined) return fallback;
    throw new Error(`Missing content file: ${filePath}`);
  }
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

/**
 * Loads every content file at once.
 *
 * Call it at the start of a build or script. The result is the raw data,
 * exactly as written in the files; pass it to buildCatalog() in
 * lib/catalog.js to get page-ready structures.
 *
 * @returns {{site: object, categories: object[], articles: object[],
 *            quotes: object[], people: object[], vizzes: object}}
 */
function loadContent() {
  return {
    site: loadYaml("site.yaml"),
    categories: loadYaml("categories.yaml"),
    articles: loadYaml("articles.yaml"),
    quotes: loadYaml("quotes.yaml", []),
    people: loadYaml("people.yaml", []),
    // Generated by `npm run fetch:vizzes`; keyed by the person slug in people.yaml.
    vizzes: loadJson("vizzes.json", {}),
  };
}

module.exports = { CONTENT_DIR, loadYaml, loadJson, loadContent };
